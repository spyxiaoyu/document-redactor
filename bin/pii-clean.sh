#!/usr/bin/env bash
# pii-clean.sh: 一次性 git history PII 清理（替代手动 filter-branch 4 轮）
#
# 【2026-07-29 创建】教训：
#   之前 PII 清理手动跑 filter-branch 4 轮（hash 链 5c185b7 → 32d6d26 → 7e1ef56
#   → 5cd4560 → e899d36），每次改 hash 浪费工作量。本脚本封装一次性完整 SOP：
#
#   1. tree-filter：perl 替换 26 类 PII（最长优先）
#   2. msg-filter：perl 替换 commit message 同样 26 类
#   3. 物理删 dangling commit + refs/original/
#   4. 4 维度验证：reachable refs / dangling / .git/objects/pack / working tree
#
# 用法：
#   bash bin/pii-clean.sh /tmp/pii-patterns.txt
#
# 前提：
#   - git-filter-repo 不可用（PEP 668 拦），用内置 filter-branch
#   - 备份：脚本自动 cp -r .git → .git.bak.pre-clean-<timestamp>
#   - 必须未 push 到远端（无 force-push 风险）
#
# 设计要点：
#   - perl script 用 .pl 文件，pattern 从 $ENV{PII_PATTERNS_FILE} 读
#     （不嵌进 perl source = 避开 3 层 shell escape 灾难，2026-07-29 教训）
#   - tree-filter 直接调 `perl $PERL_SCRIPT`（filter-branch 喂文件内容到 stdin）
#   - replacement 用 string var，只 escape 反斜杠
#   - 替换顺序：最长优先（避免子串误伤 Tian Gan code 辛公司/癸公司）
#   - 后置清理：`git reflog expire --expire=now --all` + `git gc --prune=now --aggressive`
#     + `git for-each-ref refs/original/ | xargs git update-ref -d`
#   - 4 维度验证：reachable + dangling + .git/objects/pack + working tree
#     各自 grep 26 类 PII pattern，全部应 0 命中
#
# 注：本脚本 idempotent — 已 clean 的 repo 跑完仍然 0 PII（filter-branch 检测
# no-op ref 报 "Ref unchanged" 是预期行为）。

set -uo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null)"
if [ -z "$REPO_ROOT" ]; then
  echo "❌ pii-clean.sh: 不是 git 仓库" >&2
  exit 2
fi

cd "$REPO_ROOT"

# 强制环境变量 UTF-8
export LANG=en_US.UTF-8
export LC_ALL=en_US.UTF-8

PATTERN_FILE="${1:-/tmp/pii-patterns.txt}"
if [ ! -f "$PATTERN_FILE" ]; then
  echo "❌ pii-clean.sh: PII pattern 文件不存在: $PATTERN_FILE" >&2
  echo "   每个 pattern 一行（固定字符串）。脚本会按长度倒序逐个替换。" >&2
  echo "   格式示例：<from>	<to>" >&2
  exit 2
fi

# 临时目录：放 perl script
TMPDIR=$(mktemp -d /tmp/pii-clean-XXXXXX)
trap 'rm -rf "$TMPDIR"' EXIT

PERL_SCRIPT="$TMPDIR/replace-pii.pl"

# 1. 生成 perl 替换脚本
# 设计：pattern 放 $PATTERN_FILE（bash 直接写，无 escape 噩梦），
# perl script 从 $ENV{PII_PATTERNS_FILE} 读。最长优先。
# 关键：replacement 用 string var（perl s/PAT/STR/g 自动 string 替换，不当 regex），
# 只需 escape 反斜杠。不嵌 pattern 进 perl source = 不踩 3 层 escape 坑。
# （2026-07-29 教训：第一版嵌 pattern 进 perl source 又嵌进 bash wrapper，
#  导致 ① sprintf('%q', "$to") 在 bash 里把空 $to 变 %q、② wrapper 引号嵌套乱）
# UTF-8：命令行用 `-CSD` flag（STDIN/STDOUT/ARGV 全 UTF-8），脚本里 `use utf8` 让
# source code 里的中文 literal 当 UTF-8 处理。
cat > "$PERL_SCRIPT" <<'PERL_HEADER'
#!/usr/bin/perl
# Auto-generated by bin/pii-clean.sh — 从 $ENV{PII_PATTERNS_FILE} 读 PII pattern
use strict;
use warnings;
use utf8;

my $patterns_file = $ENV{PII_PATTERNS_FILE} or die "PII_PATTERNS_FILE not set\n";
open(my $fh, '<:utf8', $patterns_file) or die "Cannot open $patterns_file: $!\n";
my @patterns;
while (my $line = <$fh>) {
  chomp $line;
  next unless $line =~ /\t/;
  my ($from, $to) = split /\t/, $line, 2;
  push @patterns, [$from, $to];
}
close $fh;

# 按 from 长度倒序（避免子串误伤 Tian Gan code 辛公司/癸公司）
@patterns = sort { length($b->[0]) <=> length($a->[0]) } @patterns;

while (<>) {
  for my $p (@patterns) {
    my ($from, $to) = @$p;
    my $re = qr/\Q$from\E/;
    # perl s/// 替换串是 string，$to 直接插值；只 escape 反斜杠
    (my $to_safe = $to) =~ s/\\/\\\\/g;
    s/$re/$to_safe/g;
  }
  print;
}
PERL_HEADER
chmod +x "$PERL_SCRIPT"

echo "==> 生成 perl script: $PERL_SCRIPT ($(wc -l < "$PERL_SCRIPT") 行)"
echo ""

# 2. 物理备份
if [ -d .git ]; then
  BACKUP_DIR=".git.bak.pre-clean-$(date +%s)"
  echo "==> 备份 .git/ 到 $BACKUP_DIR"
  cp -r .git "$BACKUP_DIR"
  echo ""
fi

# 3. tree-filter（文件内容）：filter-branch checkout tree 到临时目录 + 跑 command + commit 回去。
#    必须 in-place edit working tree（不靠 stdin/stdout）— 用 find + xargs + perl -i。
#    .git/ 目录排除（pack 是 zlib binary，UTF-8 解析警告污染输出）。
export PII_PATTERNS_FILE="$PATTERN_FILE"
echo "==> Step 1: filter-branch --tree-filter (file content)"
FILTER_BRANCH_SQUELCH_WARNING=1 git filter-branch -f \
  --tree-filter "find . -path ./.git -prune -o -type f -print0 | xargs -0 perl -CSD -i $PERL_SCRIPT" \
  --tag-name-filter cat -- --all 2>&1 | tail -3
echo ""

# 4. msg-filter（commit message body）：filter-branch 喂 commit message 到 stdin，
#    perl 读 stdin 处理后写 stdout（不用 -i，天然 work）
echo "==> Step 2: filter-branch --msg-filter (commit message body)"
FILTER_BRANCH_SQUELCH_WARNING=1 git filter-branch -f \
  --msg-filter "perl -CSD $PERL_SCRIPT" \
  --tag-name-filter cat -- --all 2>&1 | tail -3
echo ""

# 5. 物理删 dangling + 回滚通道
echo "==> Step 3: 清理 dangling + refs/original/"
git for-each-ref --format='%(refname)' refs/original/ 2>/dev/null | xargs -n1 git update-ref -d 2>/dev/null || true
git reflog expire --expire=now --all
git gc --prune=now --aggressive 2>&1 | tail -3
echo ""

# 6. 4 维度验证
echo "==> Step 4: 4 维度验证"

# 准备：把所有 pattern 存到 PII_PATTERNS array（避免 while-loop 内重读文件）
# 注意：读的是 from 列（不含 tab 后的 to）— grep -F 完整字符串匹配
PII_PATTERNS=()
while IFS=$'\t' read -r from _; do
  [ -n "$from" ] && PII_PATTERNS+=("$from")
done < "$PATTERN_FILE"

# (1) reachable refs commit messages
echo "  (1) reachable refs commit messages:"
total=0
for p in "${PII_PATTERNS[@]}"; do
  n=$(git log --all --format='%B' 2>/dev/null | LC_ALL=C grep -F -c -- "$p" 2>/dev/null) || n=0
  [ -z "$n" ] && n=0
  total=$((total + n))
done
[ "$total" = "0" ] && echo "    ✅ 0 命中" || echo "    ❌ $total"

# (2) reachable refs file content diff（只扫 + 行，不翻旧行）
# 注：macOS BSD grep 对 '^\+' 解析失败（即使 -E），用 '+'（BRE literal char）替代
echo "  (2) reachable refs file content diff:"
total2=0
for p in "${PII_PATTERNS[@]}"; do
  n=$(git log -p --all 2>/dev/null | grep '^+' | grep -v '^+++' | LC_ALL=C grep -F -c -- "$p" 2>/dev/null) || n=0
  [ -z "$n" ] && n=0
  total2=$((total2 + n))
done
[ "$total2" = "0" ] && echo "    ✅ 0 命中" || echo "    ❌ $total2"

# (3) .git/objects/pack
echo "  (3) .git/objects/pack:"
total3=0
for p in "${PII_PATTERNS[@]}"; do
  n=$(LC_ALL=C grep -F -c -- "$p" .git/objects/pack/*.pack 2>/dev/null | awk -F: '{s+=$2}END{print s+0}') || n=0
  [ -z "$n" ] && n=0
  total3=$((total3 + n))
done
[ "$total3" = "0" ] && echo "    ✅ 0 命中" || echo "    ❌ $total3"

# (4) working tree
echo "  (4) working tree:"
total4=0
for p in "${PII_PATTERNS[@]}"; do
  n=$(git ls-files | xargs LC_ALL=C grep -F -c -- "$p" 2>/dev/null | awk -F: '{s+=$2}END{print s+0}') || n=0
  [ -z "$n" ] && n=0
  total4=$((total4 + n))
done
[ "$total4" = "0" ] && echo "    ✅ 0 命中" || echo "    ❌ $total4"

# 7. 报告
total_all=$((total + total2 + total3 + total4))
echo ""
if [ "$total_all" = "0" ]; then
  echo "✅✅✅ pii-clean.sh 全部 4 维度 0 PII 命中"
  echo ""
  echo "下一步："
  echo "  git log --oneline | head -3  # 验证新 hash"
  echo "  npx vitest run               # 验证测试"
  echo "  rm -rf .git.bak.pre-clean-*  # 验证通过后删备份"
else
  echo "❌❌❌ pii-clean.sh 仍有 $total_all 处 PII 残留"
fi